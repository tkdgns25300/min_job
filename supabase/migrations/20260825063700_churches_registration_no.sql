-- 교회를 **고유번호**로 특정한다 — `churches`에 유일키가 생긴다.
--
-- 지금까지 `churches`의 유일 제약은 랜덤 `id`뿐이라, **같은 교회로 두 행이 생기는 것을 막는 것이
-- 아무것도 없었다.** 한 교회에 담당자가 여럿 붙을 수 있으므로(DATA §3 users) 두 번째 담당자가
-- 기존 행에 붙지 못하면 그 순간 공고가 두 교회로 갈린다.
--
-- 이름으로 묶는 길은 이미 막혔다(2026-08-06 실측): (교회명+광역) 1,203그룹 중 **검증 불가 67개**,
-- **같은 연락처에 다른 교회명 83건**(`대구대동교회`/`대동교회` 표기 차이 + 교단 사무실 공유).
-- 사람이 봐도 판정이 안 되는 구간이 남아, 확신 없는 행을 만드느니 안 만드는 쪽을 택했었다.
--
-- 고유번호(고유번호증) 또는 사업자등록번호는 세무서가 발급한 **교회당 하나**의 번호다.
-- ⚠️ 2026-08-05에는 이 번호를 저장하지 않기로 했었다 — 근거는 "저장하면 보관 부담만 진다"였다.
--    **그 전제가 바뀌었다**(2026-08-25 운영자 결정): 증빙 서류 자체를 인증 자격이 유지되는 동안
--    보관하기로 했으므로 번호는 어차피 우리 손에 있다. 컬럼으로 꺼내면 보관 항목은 그대로인데
--    **자동 판별이 생긴다.** 개인정보처리방침 §1(수집 항목)·§3(보유 기간)을 함께 고쳤다.
--
-- **하이픈 없이 숫자 10자리만 저장한다.** 안 그러면 `123-45-67890`과 `1234567890`이 서로 다른
-- 교회가 되어 UNIQUE가 무의미해진다. 하이픈은 화면에서만 넣는다.
--
-- 체크섬은 검사하지 않는다 — 사업자등록번호 체크섬 규칙이 비영리 고유번호에 그대로 들어맞지
-- 않아, 잘못 막으면 진짜 교회가 신청을 못 한다. 진짜 대조는 운영자가 증빙 서류로 한다.
--
-- NOT NULL로 두는 근거: `churches` 행이 생기는 경로는 **교회 인증 신청 하나뿐**이고(DATA §3)
-- 신청은 증빙 서류가 필수라 번호가 항상 있다. 적용 시점 행 수는 0이라 기존 데이터 문제도 없다.

alter table churches
  add column registration_no text not null;

alter table churches
  add constraint churches_registration_no_key unique (registration_no);

alter table churches
  add constraint churches_registration_no_check
  check (registration_no ~ '^[0-9]{10}$');
